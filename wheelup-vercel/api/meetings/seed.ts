function simpleScore(text: string, isLeader: boolean) {
  const len = text.length;
  const has = (kw: string) => text.includes(kw) ? 1 : 0;

  let needs = 3 + has("本音") + has("深掘り") + has("転職理由") + has("転職動機") + has("希望") + has("キャリア") + has("不満");
  let proposal = 2 + has("具体的") + has("企業") + has("求人") + has("提案") + has("選択肢") + has("ポジション") + has("年収");
  let trust = 2 + has("業界") + has("構造") + has("経験") + has("知識") + has("市場") + has("正直") + has("現実");
  let closing = 2 + has("来週") + has("次回") + has("LINE") + has("設定") + has("約束") + has("スケジュール") + has("送付");
  let intel = 2 + has("他社") + has("エージェント") + has("選考") + has("温度感") + has("並行") + has("年収") + has("資格");

  if (len > 800) { needs += 1; proposal += 1; trust += 1; }
  if (len > 1500) { needs += 1; proposal += 1; }

  if (isLeader) {
    needs = Math.min(10, needs + 2);
    proposal = Math.min(10, proposal + 1);
    trust = Math.min(10, trust + 1);
    closing = Math.min(10, closing + 2);
    intel = Math.min(10, intel + 1);
  }

  needs = Math.min(10, needs);
  proposal = Math.min(10, proposal);
  trust = Math.min(10, trust);
  closing = Math.min(10, closing);
  intel = Math.min(10, intel);

  const total = needs + proposal + trust + closing + intel;
  const grade = total >= 40 ? "S" : total >= 35 ? "A" : total >= 25 ? "B" : "C";

  return {
    scores: { needs, proposal, trust, closing, intel },
    total,
    grade,
    evidence: {
      needs: text.includes("本音") ? "候補者の本音を引き出している" : "ニーズの確認を実施",
      proposal: text.includes("具体的") ? "具体的な企業・ポジションを提示" : "提案内容あり",
      trust: text.includes("業界") ? "業界知識を活かした信頼構築" : "専門的な説明を実施",
      closing: text.includes("次回") ? "次回面談を設定し行動を促進" : "アクション設定あり",
      intel: text.includes("他社") ? "他社エージェントの状況を確認" : "情報収集を実施",
    },
    strengths: isLeader
      ? ["業界構造の深い知識に基づく具体的な提案", "候補者の本音を引き出す質問力"]
      : ["基本的なヒアリングが実施できている"],
    improvements: isLeader
      ? ["さらなるクロージング強化の余地あり"]
      : ["具体的な企業提案を増やす", "業界知識を深めて信頼を構築する"],
  };
}

export default async function handler(req: VercelRequest, res: VercelResponse) {
  if (req.method !== "POST" && req.method !== "GET") {
    return res.status(405).json({ error: "GET or POST" });
  }

  const db = getSupabaseAdmin();

  const { data: existing } = await db
    .from("meeting_transcripts")
    .select("id")
    .eq("is_leader", true)
    .limit(1);

  if (existing && existing.length > 0) {
    return res.json({
      message: "リーダーデータは既に存在します。重複投入を防止しました。",
      skipped: true,
    });
  }

  const allMeetings = [...LEADER_MEETINGS, ...MEMBER_MEETINGS];
  const results: Array<{ id?: string; title: string; grade?: string; error?: string }> = [];

  for (let i = 0; i < allMeetings.length; i++) {
    const m = allMeetings[i];
    const daysAgo = Math.floor(Math.random() * 14) + 1;
    const recordedAt = new Date(Date.now() - daysAgo * 24 * 60 * 60 * 1000).toISOString();
    const scoreData = simpleScore(m.text, m.is_leader);

    const { data, error } = await db.from("meeting_transcripts").insert({
      consultant_name: m.consultant_name,
      is_leader: m.is_leader,
      title: m.title,
      transcript_text: m.text,
      score_data: scoreData,
      source: "seed",
      recorded_at: recordedAt,
    }).select("id, title").single();

    if (error) {
      results.push({ title: m.title, error: error.message });
    } else {
      results.push({ id: data.id, title: data.title, grade: scoreData.grade });
    }
  }

  const leaderCount = results.filter((_, i) => i < LEADER_MEETINGS.length && !("error" in results[i])).length;
  const memberCount = results.filter((_, i) => i >= LEADER_MEETINGS.length && !("error" in results[i])).length;

  return res.json({
    message: `シード完了: リーダー面談 ${leaderCount}件 + メンバー面談 ${memberCount}件`,
    results,
  });
}
